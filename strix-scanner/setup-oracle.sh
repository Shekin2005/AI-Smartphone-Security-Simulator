#!/usr/bin/env bash
# ==================================================
# STRIX SCANNER - ORACLE CLOUD ALWAYS FREE (ARM) SETUP
# ==================================================
# Run this ON the Oracle VM, as a normal sudo-capable user:
#
#   curl -fsSL https://raw.githubusercontent.com/Shekin2005/AI-Smartphone-Security-Simulator/main/strix-scanner/setup-oracle.sh -o setup-oracle.sh
#   bash setup-oracle.sh
#
# It is idempotent: safe to run twice.
#
# What it does
#   1. installs Docker (native, not nested)
#   2. clones or updates the project
#   3. writes strix-scanner/.env with a shared token + your public site
#   4. builds and starts the scanner
#   5. prints the token and the exact Render variables to paste
#
# Strix launches one sandbox container per scan, so it needs a real
# Docker daemon. A VM gives you that; a container PaaS cannot.
# ==================================================

set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/Shekin2005/AI-Smartphone-Security-Simulator.git}"
PROJECT_DIR="${PROJECT_DIR:-$HOME/AI-Smartphone-Security-Simulator}"
PUBLIC_SITE="${PUBLIC_SITE:-https://ai-smartphone-security-simulator.onrender.com}"

say() { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
warn() { printf '\n\033[1;33m!! %s\033[0m\n' "$*"; }

if [[ $EUID -eq 0 ]]; then
  warn "Run this as a normal user with sudo rights, not as root."
  exit 1
fi

# --------------------------------------------------
# 1. Docker
# --------------------------------------------------
if command -v docker >/dev/null 2>&1; then
  say "Docker already installed: $(docker --version)"
else
  say "Installing Docker"
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "$USER"
  warn "Added $USER to the docker group. If the next step fails, log out and back in."
fi

# The group change does not apply to this shell; use sudo for compose calls.
DOCKER="sudo docker"

if ! $DOCKER info >/dev/null 2>&1; then
  warn "Docker daemon is not responding. Try: sudo systemctl start docker"
  exit 1
fi

# --------------------------------------------------
# 2. Project
# --------------------------------------------------
if [[ -d "$PROJECT_DIR/.git" ]]; then
  say "Updating existing checkout"
  git -C "$PROJECT_DIR" pull --ff-only
else
  say "Cloning project"
  git clone "$REPO_URL" "$PROJECT_DIR"
fi

SCANNER_DIR="$PROJECT_DIR/strix-scanner"
ENV_FILE="$SCANNER_DIR/.env"

# --------------------------------------------------
# 3. Scanner configuration
# --------------------------------------------------
if [[ -f "$ENV_FILE" ]] && grep -q '^STRIX_SCAN_TOKEN=..*' "$ENV_FILE"; then
  TOKEN="$(grep '^STRIX_SCAN_TOKEN=' "$ENV_FILE" | cut -d= -f2-)"
  say "Reusing existing token"
else
  TOKEN="$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  say "Generated a new shared token"
fi

cat > "$ENV_FILE" <<EOF
# Generated by setup-oracle.sh
STRIX_SCAN_TOKEN=$TOKEN

# The agent attacks your public site, not localhost: the app's Origin
# guard compares against the public origin.
TARGET_BASE=$PUBLIC_SITE
EOF

chmod 600 "$ENV_FILE"

# --------------------------------------------------
# 4. Start
# --------------------------------------------------
say "Building and starting the scanner (first build takes a few minutes)"
cd "$SCANNER_DIR"
$DOCKER compose up -d --build

say "Waiting for the scanner to answer"
for i in $(seq 1 30); do
  code="$(curl -s -o /dev/null -w '%{http_code}' -H "x-scan-token: $TOKEN" \
    http://127.0.0.1:8000/api/health || true)"
  if [[ "$code" == "200" ]]; then
    say "Scanner is healthy"
    break
  fi
  sleep 5
  if [[ "$i" == "30" ]]; then
    warn "Scanner did not answer in time. Check: $DOCKER logs strix-scanner"
    exit 1
  fi
done

# --------------------------------------------------
# 5. Publish it
# --------------------------------------------------
if command -v cloudflared >/dev/null 2>&1; then
  say "cloudflared already installed"
else
  warn "cloudflared is NOT installed - the scanner is only reachable on this VM."
  echo "   Install it with:"
  echo "     curl -fsSL https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-arm64 -o cloudflared"
  echo "     sudo install -m 755 cloudflared /usr/local/bin/cloudflared"
fi

cat <<EOF

==============================================================
 SCANNER IS RUNNING
==============================================================
 Shared token:
   $TOKEN

 Paste BOTH of these into Render -> your service -> Environment,
 then let it redeploy:

   STRIX_SCAN_TOKEN   = $TOKEN
   STRIX_SCANNER_URL  = https://<your-tunnel-hostname>

 Start the tunnel on this VM:

   cloudflared tunnel --url http://localhost:8000

 Copy the https://....trycloudflare.com hostname it prints and use it
 as STRIX_SCANNER_URL.

 Note: trycloudflare URLs are temporary. For a stable hostname, create
 a named Cloudflare tunnel, or open port 8000 in the Oracle security
 list and put Caddy in front of it.
==============================================================
EOF
